CREATE TABLE IF NOT EXISTS rf_role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
    name VARCHAR(80) UNIQUE NOT NULL
);
INSERT INTO rf_role (id, name) SELECT 1, 'System Admin'
WHERE NOT EXISTS (SELECT 1 FROM rf_role WHERE id = 1);
CREATE TABLE IF NOT EXISTS rf_profile (
    username VARCHAR(64) PRIMARY KEY,
    password_hash VARCHAR(128) NOT NULL,
    role_id BIGINT NOT NULL REFERENCES rf_role(id),
    credential_version BIGINT DEFAULT 1 NOT NULL
);
CREATE TABLE IF NOT EXISTS rf_grant (
    role_id BIGINT NOT NULL REFERENCES rf_role(id) ON DELETE CASCADE,
    kind VARCHAR(8) NOT NULL,
    resource_id VARCHAR(32) NOT NULL,
    PRIMARY KEY (role_id, kind, resource_id)
);
ALTER TABLE rf_profile ADD COLUMN IF NOT EXISTS active BOOLEAN DEFAULT TRUE NOT NULL;
